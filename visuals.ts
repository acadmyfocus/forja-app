export function visualFor(person: Character): string {
  const canon = canonicalLooks[person.name];
  if (canon) return `, ${canon}`;
  const parts: string[] = [];
  if (person.armor !== "Nenhuma") parts.push(`wearing ${person.armor}`);
  if (person.weapons !== "Nenhuma" && person.weapons !== "Punhos") parts.push(`armed with ${person.weapons}`);
  parts.push(`known for ${person.powers.slice(0, 2).join(" and ").toLowerCase()}`);
  return `, ${parts.join(", ")}, authentic comic book costume`;
}
